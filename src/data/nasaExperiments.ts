export const RANKING_WEIGHTS = {
  crewSafetyDirectness: 0.30,
  habitatApplicability: 0.25,
  telemetryFidelity: 0.15,
  materialBreadth: 0.15,
  hardwareHeritage: 0.08,
  recency: 0.07,
} as const;

export function computeCrewSafetyRelevance(criteria: RelevanceCriteria): number {
  const score =
    criteria.crewSafetyDirectness * RANKING_WEIGHTS.crewSafetyDirectness +
    criteria.habitatApplicability * RANKING_WEIGHTS.habitatApplicability +
    criteria.telemetryFidelity * RANKING_WEIGHTS.telemetryFidelity +
    criteria.materialBreadth * RANKING_WEIGHTS.materialBreadth +
    criteria.hardwareHeritage * RANKING_WEIGHTS.hardwareHeritage +
    criteria.recency * RANKING_WEIGHTS.recency;
  return Number(score.toFixed(1));
}

